"""Emit machine artifacts (evidence, progress) and generated human documents (TODO, RUNBOOK)."""

from __future__ import annotations

import datetime as dt
from pathlib import Path
from typing import Any

import yaml

from identity import sha256_text
from registry import REGISTRY, Context, Instrument, argv, default_targets
from schema import EVIDENCE_SCHEMA, PROGRESS_SCHEMA, SEVERITIES, Record

BANNER = "<!-- GENERATED SECTION. DO NOT HAND-EDIT. Regenerated by `uv run --project hunt hound run`. -->"


def stamp() -> str:
    return dt.datetime.now(dt.UTC).replace(microsecond=0).isoformat()


def dump(doc: dict[str, Any]) -> str:
    return yaml.safe_dump(doc, sort_keys=False, allow_unicode=False, width=120)


def evidence(
    target: dict[str, Any],
    scope_digest: str,
    provenance_digest: str,
    records: list[Record],
    liveness: list[dict[str, Any]],
    gaps: list[dict[str, Any]],
) -> dict[str, Any]:
    by_severity = dict.fromkeys(SEVERITIES, 0)
    by_instrument: dict[str, int] = {}
    for record in records:
        by_instrument[record.instrument] = by_instrument.get(record.instrument, 0) + len(record.issues)
        for issue in record.issues:
            by_severity[issue.severity] += 1
    return {
        "schema": EVIDENCE_SCHEMA,
        "generated": stamp(),
        "target": target,
        "scope_digest": scope_digest,
        "provenance_digest": provenance_digest,
        "summary": {
            "records": len(records),
            "issues": sum(len(r.issues) for r in records),
            "by_severity": by_severity,
            "by_instrument": dict(sorted(by_instrument.items())),
            "by_status": {s: sum(1 for r in records if r.status == s) for s in ("ok", "blocked", "timeout", "failed")},
            "liveness_ok": all(bool(e.get("clean")) and bool(e.get("positive")) for e in liveness),
            "gaps": len(gaps),
        },
        "records": [r.to_dict() for r in records],
        "liveness": liveness,
        "gaps": gaps,
    }


def write(path: Path, doc: dict[str, Any]) -> str:
    text = dump(doc)
    path.write_text(text, "utf-8")
    return sha256_text(text)


def progress(hunt: Path, phases: list[dict[str, Any]]) -> str:
    doc = {
        "schema": PROGRESS_SCHEMA,
        "generated": stamp(),
        "note": "derived cache; the disk wins on every disagreement and every local check reruns on every invocation",
        "phases": phases,
    }
    return write(hunt / "progress.yaml", doc)


def todo(hunt: Path, evidence_doc: dict[str, Any], verdict: dict[str, Any] | None) -> None:
    lines = ["# HOUND backlog", "", BANNER, "", f"Generated {stamp()}.", ""]
    gaps = evidence_doc.get("gaps") or []
    lines.append("## Coverage gaps (each caps the disposition)")
    lines.append("")
    if not gaps:
        lines.append("- none recorded")
    for gap in gaps:
        lines.append(f"- [ ] {gap.get('surface')}: {gap.get('gap')} (cap {gap.get('cap')})")
    lines.append("")
    lines.append("## Instruments that did not run clean")
    lines.append("")
    bad = [r for r in evidence_doc.get("records") or [] if r.get("status") != "ok" or r.get("parser") == "failed"]
    if not bad:
        lines.append("- none")
    for record in bad:
        lines.append(
            (
                f"- [ ] {record.get('instrument')}: status {record.get('status')}, "
                f"parser {record.get('parser')}, {record.get('note') or ''}"
            ).rstrip()
        )
    lines.append("")
    lines.append("## Liveness")
    lines.append("")
    for entry in evidence_doc.get("liveness") or []:
        flag = "ok" if entry.get("clean") and entry.get("positive") else "BROKEN"
        lines.append(
            f"- [{'x' if flag == 'ok' else ' '}] {entry.get('instrument')}: "
            f"clean={entry.get('clean')} positive={entry.get('positive')}"
        )
    lines.append("")
    if verdict:
        lines.append("## Verifier")
        lines.append("")
        lines.append(f"- computed disposition: {verdict.get('computed')}")
        for reason in verdict.get("caps") or []:
            lines.append(f"- [ ] cap: {reason}")
        for reason in verdict.get("rejections") or []:
            lines.append(f"- [ ] rejection: {reason}")
        lines.append("")
    lines.append("## Open items by severity")
    lines.append("")
    summary = (evidence_doc.get("summary") or {}).get("by_severity") or {}
    for severity in reversed(SEVERITIES):
        lines.append(f"- {severity}: {summary.get(severity, 0)}")
    lines.append("")
    (hunt / "TODO.md").write_text("\n".join(lines), "utf-8")


def runbook(hunt: Path, ctx: Context | None, instruments: list[Instrument]) -> None:
    lines = ["# HOUND runbook", "", BANNER, "", f"Generated {stamp()} from the instrument registry.", ""]
    lines.append("## Commands")
    lines.append("")
    lines.append("```")
    lines.append("uv sync --project hunt")
    lines.append("uv run --project hunt hound provision")
    lines.append("uv run --project hunt hound run")
    lines.append("uv run --project hunt hound verify --findings hunt/findings.yaml --context hunt/evidence.yaml")
    lines.append("uv run --project hunt ruff check hunt && uv run --project hunt ruff format --check hunt")
    lines.append("uv run --project hunt mypy --config-file hunt/pyproject.toml")
    lines.append("uv run --project hunt pytest hunt/test")
    lines.append("```")
    lines.append("")
    lines.append("## Registry")
    lines.append("")
    lines.append(
        "| instrument | category | kind | ecosystems | conditions | required | database | cap when absent | timeout |"
    )
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for i in REGISTRY:
        lines.append(
            f"| {i.name} | {i.category} | {i.kind} | {', '.join(i.ecosystems)} | {', '.join(i.conditions) or '-'} | "
            f"{i.required} | {i.database} | {i.cap_when_absent} | {i.timeout_s}s |"
        )
    lines.append("")
    lines.append("## Selected for this target")
    lines.append("")
    if ctx is None:
        lines.append("- scope not built yet")
    for i in instruments:
        if ctx is None:
            break
        command = " ".join(argv(i, ctx, default_targets(i, ctx), ctx.results / "raw" / f"{i.name}.json"))
        lines.append(f"- {i.name}: `{command}`")
    lines.append("")
    lines.append("## Rules")
    lines.append("")
    lines.append("- the target tree is read-only; HOUND writes under hunt/, QUARRY.md, and one .gitignore entry")
    lines.append("- hunt/evidence.yaml is the only citable source; findings cite record ids and issue ids")
    lines.append("- scanner databases are pinned under hunt/rule and hunt/results/trivy; `--config auto` is forbidden")
    lines.append("- credentials in the environment are stripped before any child process starts")
    lines.append("- a blocked or absent required instrument caps the disposition; it is never skipped silently")
    lines.append("")
    (hunt / "RUNBOOK.md").write_text("\n".join(lines), "utf-8")
